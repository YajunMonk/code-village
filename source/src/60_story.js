async function complete(i) {
  G.done = i + 1; save(true);
  const w = walls.find(w => w.zone === i);
  if (w) {
    Audio.sfx('wall'); shake(4);
    for (let y = 4 * TILE; y < 26 * TILE; y += 6) burst(w.x + 8, y, 3, { colors: ['#ff2fa0', '#22e6d0', '#ffffff', '#b07aff'], min: 20, max: 120, life: 1.2, size: 2, glow: true });
    toast('乱码墙消失了！往右走 →');
  }
  if (BOSS_ZONES[i]) Audio.play(zoneMusic(curZone));
  if (BOSS_LIST.includes(i)) {
    const h = REGIONS[regionOf(i)].hat;
    if (!G.hats.includes(h)) G.hats.push(h);
    G.hat = h; appNew = true; save();
    Audio.sfx('jingle');
    await talk([['xa', `收到一顶${HATS[h].n}。看看点单页现在能做什么了。`]]);
    await openApp(true);
  }
}

